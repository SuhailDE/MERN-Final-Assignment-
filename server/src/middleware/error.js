export const notFound = (req, res) => res.status(404).json({ message: `Route not found: ${req.originalUrl}` });

export const errorHandler = (err, req, res, next) => {
  let status = err.status || 500;
  let message = err.message || 'Server error';

  if (err.name === 'ValidationError') {
    status = 400;
    message = Object.values(err.errors).map((e) => e.message).join(', ');
  } else if (err.name === 'CastError') {
    status = 400;
    message = 'Invalid ID';
  } else if (err.code === 11000) {
    status = 409;
    message = err.keyPattern?.email ? 'Email is already registered' : 'Already exists';
    if (err.keyPattern?.job) message = 'You have already applied to this job';
  }
  if (status === 500) console.error(err);
  res.status(status).json({ message });
};
